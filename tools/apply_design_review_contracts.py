#!/usr/bin/env python3
"""Update the block contracts for the 2026-11-10 design-review changes.

The contracts stay the reviewed assignment source that
tools/check_schematic_contracts.py compares with the exported netlist.
One-shot edit; run on the pre-review contracts.
"""
import json
import pathlib

D = pathlib.Path(__file__).resolve().parents[1] / 'docs/design'
NOTE = 'design review 2026-11-10'
STD = 'standard KiCad library footprint; verify against the exact part drawing before fabrication'


def load(b):
    return json.loads((D / f'{b}_contract.json').read_text())


def save(b, d):
    (D / f'{b}_contract.json').write_text(json.dumps(d, indent=2, ensure_ascii=False) + '\n')


def drop(d, refs, keys=('components', 'two_terminal_support')):
    for k in keys:
        if k in d:
            d[k] = [c for c in d[k] if c['ref'] not in refs]


def get(d, ref):
    for k in ('components', 'two_terminal_support'):
        for c in d.get(k, []):
            if c['ref'] == ref:
                return c
    raise KeyError(ref)


# ---- power
p = load('power')
drop(p, {'U107', 'C115', 'R129', 'R130', 'Q103', 'R110', 'R103', 'R104', 'R105', 'R106', 'R120', 'J104', 'R115'})
get(p, 'U101')['pins'].update({'4': 'GND', '5': 'GND', '9': None})
get(p, 'U102')['pins'].update({'1': 'BATT_NTC', '4': 'GND', '7': None})
for ref, val in {'R107': '30k 1%', 'R108': '10k 1%', 'R109': '82k 1%', 'R112': '4.3k 1%', 'R113': '3.3k 1%',
                 'R114': '47k 1%', 'R117': '56k 1%', 'R118': '10k 1%', 'R127': '1M 1%', 'R128': '1M 1%',
                 'C116': '100nF 6.3V X7R'}.items():
    get(p, ref)['value'] = val
get(p, 'R127')['pins'] = {'1': 'VBAT_PROTECTED', '2': 'BAT_ADC'}
get(p, 'R128')['pins'] = {'1': 'BAT_ADC', '2': 'GND'}
get(p, 'C116')['pins'] = {'1': 'BAT_ADC', '2': 'GND'}
p['two_terminal_support'].append({
    'ref': 'RT101', 'kind': 'R', 'value': '10k NTC B3950 1%', 'pins': {'1': 'BATT_NTC', '2': 'GND'}, 'fitted': True,
    'note': 'Board NTC placed inside the cell footprint; BQ24074 TS window is roughly 3-47 degC nominal with B3950. ' + NOTE,
    'footprint': 'Resistor_SMD:R_0603_1608Metric', 'footprint_status': STD})
u105 = get(p, 'U105'); u105['pins'] = {'1': 'USB_CC2', '2': 'USB_DP', '3': 'GND', '4': 'USB_DM', '5': 'USB_CC1', '6': 'USB_CC1', '7': 'USB_DM', '8': 'GND', '9': 'USB_DP', '10': 'USB_CC2'}; u105['footprint'] = 'Package_SON:USON-10_2.5x1.0mm_P0.5mm'; u105['footprint_status'] = STD
j102 = get(p, 'J102')
j102.update({'mpn': 'S2B-PH-K-S(LF)(SN)', 'status': 'JST PH through-hole side entry on the rear; pin 1 battery positive; pack polarity must be checked',
             'footprint': 'Connector_JST:JST_PH_S2B-PH-K_1x02_P2.00mm_Horizontal', 'footprint_status': STD})
j103 = get(p, 'J103')
j103.update({'mpn': 'PCB pads only: no fitted component', 'status': 'two rear ENIG pads, 8 mm pitch; dock contact design pending',
             'footprint': 'Tinkerbadge:Dock_Pads_2x_4x6mm', 'footprint_status': 'project footprint generated by tools/create_review_footprints.py'})
l101 = get(p, 'L101')
l101.update({'mpn': 'XFL4015-471MEB', 'footprint': 'Inductor_SMD:L_Coilcraft_XxL4020', 'footprint_status': STD,
             'note': 'TI TPS63802 reference inductor family; confirm saturation/DCR against the final load envelope. ' + NOTE})
p['variant'] = 'charging enabled, on-board NTC, USB500 input limit (' + NOTE + ')'
save('power', p)

# ---- display
d = load('display')
drop(d, {'U301', 'C312', 'R303', 'R304', 'R305', 'R306', 'R307'})
j = get(d, 'J301'); j['exact_mpn'] = 'FH12-24S-0.5SH(55)'
for pin in j['pins']:
    if pin['net'] and pin['net'].endswith('_PANEL'):
        pin['net'] = pin['net'][:-6]
j['footprint'] = 'Connector_FFC-FPC:Hirose_FH12-24S-0.5SH_1x24-1MP_P0.50mm_Horizontal'
l = get(d, 'L301'); l['exact_mpn'] = 'SRN4018-680M'; l['footprint'] = 'Inductor_SMD:L_Bourns-SRN4018'
d['revision'] = str(d.get('revision', '')) + ' + ' + NOTE
save('display', d)

# ---- peripherals
q = load('peripherals')
get(q, 'R508')['value'] = '200k 1%'
drop(q, {'R514', 'R515', 'R516', 'R517'})
get(q, 'U506')['pins'].update({'5': None, '9': None, '10': None, '11': None, '12': None})
c = get(q, 'C507'); c.update({'value': '27p C0G 50V', 'population': 'fitted', 'notes': 'Starting value for the 10-turn 18x13 mm coil (about 1.7 uH estimated); retune on the assembled badge'})
a = get(q, 'AE501'); a.update({'package': 'Tinkerbadge:NFC_Coil_Rear_18x13', 'notes': 'Rear 10-turn coil, 0.2/0.2 mm, estimated 1.7 uH. C507 27 pF start value; final loaded tuning required.'})
get(q, 'J502')['notes'] = 'Front-mounted host socket between role LEDs D402/D403. Top row 3V3/SDA/GPIO1, bottom row GND/SCL/GPIO2.'
save('peripherals', q)
print('contracts updated')
